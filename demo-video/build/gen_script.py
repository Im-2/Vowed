"""Writes demo-video/script.md (and the copy docs/demo-video/script.md): the scene table with footage timestamps, speed/cut, narration and
the right-hand visuals, from scenes.py, narration.json and the measured timeline."""
import json
import os

from scenes import SCENES, ORDER
from render import scene_times, CACHE
from tools import ROOT


def mmss(t):
    return f"{int(t // 60)}:{t % 60:05.2f}"


def main():
    tl = json.load(open(os.path.join(CACHE, "timeline.json"), encoding="utf-8"))
    times = scene_times(tl)
    by_scene = {}
    for s in tl["sentences"]:
        by_scene.setdefault(s["scene"], []).append(s["text"])
    rows = []
    for k, a, b in times:
        sc = SCENES[k]
        segs = "; ".join(f"{mmss(x)}-{mmss(y)} at {sp:g}x" for x, y, sp in sc["segs"])
        src = sum((y - x) / sp for x, y, sp in sc["segs"])
        fit = f"hold last frame {b - a - src:.1f}s" if b - a > src + 0.05 else (f"end cut {src - (b - a):.1f}s" if src - (b - a) > 0.05 else "exact")
        zoom = ", ".join(f"zoom {z:g}x at {s_:.1f}-{min(e, b - a):.1f}s" for s_, e, _, _, z in sc["zoom"]) or "none"
        text = " ".join(by_scene.get(k, []))
        visuals = f"**{sc['title']}**: " + " / ".join(x.replace("**", "") for x in sc["bullets"])
        if sc.get("diagram"):
            visuals += f" + diagram `{sc['diagram']}`"
        if sc.get("note"):
            visuals += f" + note “{sc['note']}”"
        rows.append(f"| {k} | {mmss(a)}-{mmss(b)} | {segs} | {fit}; {zoom} | {text} ({len(text)} chars) | {visuals} |")
    n = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "narration.json"), encoding="utf-8-sig"))
    chars = sum(len(" ".join(s["text"] for s in a["sentences"])) for a in n["acts"])
    md = f"""# Vowed demo video: script and scene plan

Generated by `demo-video/build/gen_script.py` from the scene plan and the measured narration. Video: `demo-video/vowed-demo-3min.mp4`
({tl['total']:.1f} s: intro 0:00-0:{tl['intro']:04.1f}, outro {mmss(tl['outro_start'])}-{mmss(tl['total'])}).

- Voice: ElevenLabs preset "{n['voice_name']}", model `{n['model_id']}`, settings {json.dumps(n['voice_settings'])}, seed 4242,
  6 requests (one per act) joined with `previous_request_ids` + `next_text`. Narration: **{chars} characters**.
- Footage: `demo-video/vowedd.mp4` (real device recording, 4:43). Times in the table are video time (left) and footage time (third column).
- Rules kept: footage never changes what the screen shows; speed at most 2x; a held last frame only on a static screen; key moments at 1x
  (wallet sign-in, stake choice, the camera counting to 3/3).

| Scene | Video time | Footage used | Fit and zoom | Narration | Right-hand visuals |
|---|---|---|---|---|---|
""" + "\n".join(rows) + """

## Cut from the footage
- 0:32-0:39 Today screen scrolling, 0:47-0:53 waiting before typing, 1:16-1:18 Phantom loading (the recording also jumps 13:15 to 13:18 at 1:19)
- 1:35-1:51 waiting on Today for check-ins to open (the countdown scene covers this)
- 2:01-2:06 the phone's home screen (the tester left the app; other apps were visible)
- 2:51-2:58 scrolling the plan back and forth; 3:14-3:20 the join review being scrolled; 3:31 the recording jumps 13:24 to 13:27
- **4:02-4:04 the share sheet: it shows real contact names**, so it is not used
- 4:05-4:24 Squads list, Explore and Today again (repeats); 4:40-4:43 the screen recorder's own controls

## Not shown in the footage, so not narrated as shown
- the weekly SKR leaderboard screen itself (only the "SKR rewards and streak freezes: weekly top streaks, test SKR" entry on the You screen)
- the Coach, Letters and Widget screens (only their entries on the You screen)
- the Phantom approval sheet for the first stake (the recording was paused there); the join shows Phantom's Confirm transaction sheet
"""
    for path in (os.path.join(ROOT, "demo-video", "script.md"), os.path.join(ROOT, "docs", "demo-video", "script.md")):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w", encoding="utf-8").write(md)
    print("wrote script.md")


if __name__ == "__main__":
    main()
